"""Builds the Claude connector for contributors from src/connector/server.js + src/shared/auth_core.js.

Writes (never hand-edit these):
  connector/faclon-glossary.mcpb            Claude Desktop extension (double-click to install)
  connector/faclon-glossary-connector.js    the same server as one file, for Claude Code or other MCP clients

protect.py runs this after every build, so the connector always uses the current sign-in code.
Bump VERSION when server.js changes so Claude Desktop offers the update.
"""
import json
import zipfile
from pathlib import Path

VERSION = "1.0.2"
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "connector"
MCPB = OUT / "faclon-glossary.mcpb"
JS = OUT / "faclon-glossary-connector.js"
STAMP = (2026, 1, 1, 0, 0, 0)  # fixed zip timestamps so rebuilding unchanged sources gives identical bytes

MANIFEST = {
    "manifest_version": "0.2",
    "name": "faclon-glossary",
    "display_name": "Faclon Labs solutions",
    "version": VERSION,
    "description": "Read and download Faclon Labs solution pages, get the design skill, and upload new pages (for contributors).",
    "long_description": "Signs in with your Faclon solution-site username and password. Lets Claude list the solution pages you can open, "
                        "read them, save them as HTML or PDF, fetch the Faclon design skill, and publish a new solution page you built. "
                        "Your password stays on this computer; the connector only talks to the Faclon site and GitHub. Needs the Contributor right.",
    "author": {"name": "Faclon Labs"},
    "homepage": "https://parth1087-debug.github.io/Faclon-Glossary/",
    "icon": "icon.png",
    "server": {
        "type": "node",
        "entry_point": "server/index.js",
        "mcp_config": {
            "command": "node",
            "args": ["${__dirname}/server/index.js"],
            "env": {
                "FACLON_USERNAME": "${user_config.username}",
                "FACLON_PASSWORD": "${user_config.password}",
                "FACLON_DOWNLOAD_DIR": "${user_config.download_dir}",
            },
        },
    },
    "tools": [
        {"name": "list_solutions", "description": "List the solution pages you can open"},
        {"name": "read_page", "description": "Read a solution page as text or HTML"},
        {"name": "download_pages", "description": "Save solution pages as HTML or PDF"},
        {"name": "get_design_skill", "description": "Get the Faclon design skill for building pages"},
        {"name": "upload_page", "description": "Publish a new solution page"},
    ],
    "keywords": ["faclon", "solutions", "industrial ai"],
    "compatibility": {"platforms": ["darwin", "win32", "linux"], "runtimes": {"node": ">=18.0.0"}},
    "user_config": {
        "username": {"type": "string", "title": "Faclon username", "description": "The username you use on the Faclon solution site", "required": True},
        "password": {"type": "string", "title": "Faclon password", "description": "Your Faclon solution-site password (kept on this computer)", "required": True, "sensitive": True},
        "download_dir": {"type": "directory", "title": "Downloads folder", "description": "Where downloaded pages are saved (a \"Faclon Labs\" folder is made inside it)",
                         "required": False, "default": "${HOME}/Downloads"},
    },
}


def server_js():
    core = (ROOT / "src/shared/auth_core.js").read_text(encoding="utf-8")
    srv = (HERE / "server.js").read_text(encoding="utf-8").replace("__VERSION__", VERSION)
    return "#!/usr/bin/env node\n/* Generated by src/connector/build_connector.py. Do not edit. */\n" + core + "\n" + srv


def build_bytes():
    """Returns {path: bytes} for every generated file."""
    js = server_js().encode("utf-8")
    import io
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in (("manifest.json", (json.dumps(MANIFEST, indent=2) + "\n").encode()),
                           ("icon.png", (HERE / "icon.png").read_bytes()),
                           ("server/index.js", js)):
            info = zipfile.ZipInfo(name, STAMP)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, data)
    return {MCPB: buf.getvalue(), JS: js}


def stale():
    return [p for p, b in build_bytes().items() if not p.exists() or p.read_bytes() != b]


def build():
    OUT.mkdir(exist_ok=True)
    changed = []
    for p, b in build_bytes().items():
        if not p.exists() or p.read_bytes() != b:
            p.write_bytes(b)
            changed.append(p)
    return changed


if __name__ == "__main__":
    for p in build():
        print("wrote", p.relative_to(ROOT))
